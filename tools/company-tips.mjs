#!/usr/bin/env node
// Turns the company's 每日小贴士 document (docs/company-tips.md) into app/company-tips.ts.
//   node tools/company-tips.mjs            rewrite app/company-tips.ts
//   node tools/company-tips.mjs --check    fail when app/company-tips.ts is out of date
// Document shape: a tip starts with a line **标题**; then plain lines (the text), ✅ lines (right way, shown as a
// highlight block), ❌ lines (wrong way) and one 来源: line. Headings, quotes, lists and --- are skipped.
// Ids follow document order (C-001, …), so new tips go at the end of the document, as its header says.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parseTipsDocument } from "../app/tips-doc.ts";

const root = fileURLToPath(new URL("..", import.meta.url));
const SOURCE = `${root}docs/company-tips.md`;
const TARGET = `${root}app/company-tips.ts`;

// The same parser the app uses for 导入 Tips (D-068), so the shipped tips and imported ones read a document alike.
export function parseCompanyTips(markdown) {
  return parseTipsDocument(markdown);
}

export function renderCompanyTips(tips) {
  return `// Generated by tools/company-tips.mjs from docs/company-tips.md — edit the document, then run the tool.
// The company's 每日小贴士 for sales staff, shown before the built-in usage tips (app/daily-tips.ts).
import type { Tip } from "./daily-tips.ts";

export const COMPANY_TIPS: Tip[] = ${JSON.stringify(tips, null, 2)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const output = renderCompanyTips(parseCompanyTips(readFileSync(SOURCE, "utf8")));
  if (process.argv.includes("--check")) {
    if (readFileSync(TARGET, "utf8") !== output) {
      console.error("app/company-tips.ts is out of date: run node tools/company-tips.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(TARGET, output);
    console.log(`wrote ${TARGET}`);
  }
}
