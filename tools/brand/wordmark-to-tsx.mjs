// Turns docs/brand/wordmark-cn.svg (text already converted to outlines) into app/brand-wordmark.tsx,
// so the settings page can show the wordmark without shipping fonts. Run after `build-logo.py`:
//   node tools/brand/wordmark-to-tsx.mjs
// `tests/brand-wordmark.test.mjs` fails when the two files drift apart.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const SOURCE = join(root, "docs", "brand", "wordmark-cn.svg");
export const TARGET = join(root, "app", "brand-wordmark.tsx");

// Rounds every number in a path to 2 decimals: a 744-unit-wide drawing shown at 22 px does not need more.
const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 100) / 100));

export function render(svg) {
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  const paths = [...svg.matchAll(/<path [^>]*?transform="([^"]+)"[^>]*? d="([^"]+)"/g)];
  if (!viewBox || paths.length === 0) throw new Error("wordmark-cn.svg: no viewBox or no paths");
  const body = paths.map(([, transform, d]) => `      <path transform="${transform}" d="${round(d)}" />`).join("\n");
  return `// Generated by tools/brand/wordmark-to-tsx.mjs from docs/brand/wordmark-cn.svg — do not edit by hand.
// 「Copyboxx 复制盒」as outlines (Inter Display Bold + MiSans Bold, see docs/brand/README.md). Fills with currentColor.
export const WORDMARK_VIEW_BOX = "${viewBox}";

export function BrandWordmark({ className }: { className?: string }) {
  return (
    <svg className={className} viewBox={WORDMARK_VIEW_BOX} fill="currentColor" aria-hidden="true" focusable="false">
${body}
    </svg>
  );
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(TARGET, render(readFileSync(SOURCE, "utf8")));
  console.log(`wrote ${TARGET}`);
}
