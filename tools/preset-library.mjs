#!/usr/bin/env node
// Turns the company's 标准话术库 document (Markdown) into the 话术 a build ships with (app/preset-library.ts, D-066).
//   node tools/preset-library.mjs 标准话术库.md                 rewrite app/preset-library.ts from the document
//   node tools/preset-library.mjs 标准话术库.md --json out.json  also write a company library file for a 同步码
//   node tools/preset-library.mjs --clear                       back to no built-in 话术 (the public build)
// Document shape: "## 01 开场接待" starts a folder (the number is dropped), "### 1.1 新询盘" a section, "**通用开场**" an
// entry inside the section; a section with no **…** lines is one entry. Plain lines are the message. "> " lines under a
// folder become its entries' usage note; "> " lines before the first folder and "---" are skipped.
// A folder without ### sections holds its **…** entries directly (ids STD-11-01, …).
// Ids follow the section numbers (STD-1.1-01, …), so an entry keeps its id while its text changes.
// [名字], $[金额] and other [ ] parts become fill-in blocks in the app, as in every 话术.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parseSnippetDocument } from "../app/snippet-doc.ts";

const root = fileURLToPath(new URL("..", import.meta.url));
const TARGET = `${root}app/preset-library.ts`;

// The document is read by the app's own parser, so the tool and 导入话术 (D-067) understand the same template.
export function parsePresetLibrary(markdown) {
  return parseSnippetDocument(markdown);
}

export function sharedLibraryJson(library, now = Date.now()) {
  return JSON.stringify({ format: "clipbox-shared-library", version: 1, updatedAt: now, items: library.items }, null, 2) + "\n";
}

function render(library) {
  return [
    "// Generated by tools/preset-library.mjs — do not edit by hand; run the tool on the company's 标准话术库 document.",
    "// The 话术 this build ships with (D-066). Empty in the public build; a company build fills it in. When it has items,",
    "// its folders replace the standard 话术 folders, and the app adds its entries on start like a company library.",
    "",
    "export type PresetLibrary = { folders: string[]; items: Array<{ id: string; folder: string; label: string; secret: string; scene: string; action: string; usageNote: string }> };",
    "",
    `export const PRESET_LIBRARY: PresetLibrary = ${JSON.stringify(library, null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const args = process.argv.slice(2);
  if (args[0] === "--clear") {
    writeFileSync(TARGET, render({ folders: [], items: [] }));
    console.log("app/preset-library.ts: no built-in 话术");
  } else if (args[0]) {
    const library = parsePresetLibrary(readFileSync(args[0], "utf8"));
    writeFileSync(TARGET, render(library));
    const jsonAt = args.indexOf("--json");
    if (jsonAt >= 0 && args[jsonAt + 1]) writeFileSync(args[jsonAt + 1], sharedLibraryJson(library));
    console.log(`app/preset-library.ts: ${library.items.length} 条话术, ${library.folders.length} 个目录`);
    for (const name of library.folders) console.log(`  ${name}: ${library.items.filter((item) => item.folder === name).length}`);
  } else {
    console.error("usage: node tools/preset-library.mjs <标准话术库.md> [--json out.json] | --clear");
    process.exit(1);
  }
}
